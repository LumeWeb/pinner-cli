// Command genappmanifest generates mcpapp/appsassets/manifest.json
// — the mcpcanvas.AssetSource manifest (mcpcanvas.ManifestFile) describing the
// embedded MCP App bundles under mcpapp/appsassets/dist/.
//
// The manifest follows mcpcanvas's exact schema (mcpcanvas.Manifest /
// mcpcanvas.ManifestSchemaVersion / mcpcanvas.NewEmbedSource): a manifest.json
// at the asset-source FS root whose bundles table maps each view name to the
// bundle file (relative to that root) and the lowercase hex sha256 of its
// bytes. NewEmbedSource is called on the resulting FS before writing as a
// self-check, so an output the embed seam would reject can never be produced.
//
// The generator is deterministic: bundle order is the fixed view list below
// (matching the kind in mcpapp/apps_embed.go's bundleNames; the
// permanent test mcpapp/appsmanifest_test.go pins that the two stay
// in sync), JSON is emitted with stable key order and two-space indent.
//
// The output is gitignored but must exist for `go:embed appsassets` to build;
// it is regenerated by the `jsbuild` Makefile target after the bundle copy,
// so CI and any fresh `make test`/`make build` produce it automatically.
//
// Usage (from anywhere):
//
//	go run ./build/genappmanifest
package main

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"runtime"

	"go.lumeweb.com/mcpcanvas"
)

// appViews are the exact view names the MCP App surface serves — they must
// match the keys of mcpapp/apps_embed.go's bundleNames one-for-one.
// Each maps to its self-contained ESM bundle at dist/<view>.js under the
// appsassets root. handshake.js (in the same dist dir) is deliberately not a
// view: it is not registered in bundleNames and not listed in the manifest.
var appViews = []string{
	"account-email",
	"account-password",
	"auth-sso",
	"auth-status",
	"ipfs-download",
	"ipfs-upload",
	"pin",
	"pin-list",
	"vault-browser",
	"vault-create",
	"vault-download",
	"vault-restore",
	"vault-upload",
}

// compatibility is the free-form runtime-generation marker the mcpcanvas
// host checks before loading the manifest (mcpcanvas.Manifest.Compatibility).
const compatibility = "pinner-cli-mcpapp-v1"

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "genappmanifest:", err)
		os.Exit(1)
	}
}

func run() error {
	assetsRoot, err := appsAssetsRoot()
	if err != nil {
		return err
	}

	fsys := os.DirFS(assetsRoot)
	manifest := mcpcanvas.Manifest{
		SchemaVersion: mcpcanvas.ManifestSchemaVersion,
		Compatibility: compatibility,
		Bundles:       make([]mcpcanvas.Bundle, 0, len(appViews)),
	}
	for _, view := range appViews {
		file := "dist/" + view + ".js"
		data, err := fs.ReadFile(fsys, file)
		if err != nil {
			return fmt.Errorf("read bundle for view %q: %w (run the jsbuild Makefile target first)", view, err)
		}
		if len(data) == 0 {
			return fmt.Errorf("bundle for view %q (%s) is empty", view, file)
		}
		sum := sha256.Sum256(data)
		manifest.Bundles = append(manifest.Bundles, mcpcanvas.Bundle{
			View: view,
			File: file,
			Hash: hex.EncodeToString(sum[:]),
		})
	}

	if err := manifest.Validate(); err != nil {
		return fmt.Errorf("generated manifest invalid: %w", err)
	}

	data, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return fmt.Errorf("marshal manifest: %w", err)
	}
	out := filepath.Join(assetsRoot, mcpcanvas.ManifestFile)
	if err := os.WriteFile(out, append(data, '\n'), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", out, err)
	}

	// Self-check after writing (NewEmbedSource reads manifest.json from the
	// root, so the file must exist): the generated asset source must satisfy
	// the exact mcpcanvas.EmbedSource contract it will be consumed through.
	if _, err := mcpcanvas.NewEmbedSource(fsys); err != nil {
		return fmt.Errorf("mcpcanvas.NewEmbedSource rejected generated manifest: %w", err)
	}
	fmt.Printf("genappmanifest: wrote %s (%d bundles, schema v%d)\n", out, len(manifest.Bundles), manifest.SchemaVersion)
	return nil
}

// appsAssetsRoot resolves mcpapp/appsassets relative to this file's location so
// the generator works from any working directory (the Makefile runs it from
// the repo root; `go run ./build/genappmanifest` is dir-agnostic because of
// this).
func appsAssetsRoot() (string, error) {
	_, thisFile, _, ok := runtime.Caller(0)
	if !ok {
		return "", errors.New("genappmanifest: cannot resolve source file location")
	}
	// thisFile: <repo>/build/genappmanifest/main.go -> <repo>/mcpapp/appsassets
	return filepath.Join(filepath.Dir(filepath.Dir(filepath.Dir(thisFile))), "mcpapp", "appsassets"), nil
}
